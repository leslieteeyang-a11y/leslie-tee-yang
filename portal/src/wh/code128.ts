const START_B = 104;
const STOP = 106;

/** 文字 → 线条宽度序列（含前后静区以外的部分）；有非 ASCII 字元就丢错 */
export function code128Widths(text: string): number[] {
  const codes: number[] = [START_B];
  for (const ch of text) {
    const c = ch.charCodeAt(0);
    if (c < 32 || c > 126) throw new Error(`条码不能包含「${ch}」`);
    codes.push(c - 32);
  }
  let sum = START_B;
  for (let i = 1; i < codes.length; i++) sum += codes[i] * i;
  codes.push(sum % 103, STOP);
  return codes.flatMap((v) => P[v].split("").map(Number));
}

/** 回传 SVG 字串；height = 线条高度（单位：最窄线条宽度） */
export function code128Svg(text: string, height = 40): string {
  const widths = code128Widths(text);
  const quiet = 10;
  let x = quiet;
  let bars = "";
  widths.forEach((w, i) => {
    if (i % 2 === 0) bars += `M${x} 0h${w}v${height}h-${w}z`;
    x += w;
  });
  const total = x + quiet;
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${total} ${height}" preserveAspectRatio="none" shape-rendering="crispEdges"><path d="${bars}" fill="#000"/></svg>`;
}
